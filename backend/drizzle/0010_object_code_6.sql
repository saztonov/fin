-- 0010: код объекта расширен до 6 символов.
--
-- Изначально код объекта был задан как varchar(5). Заказчику этого не хватает:
-- нумерация объектов доросла до шестизначных кодов. Изменение чисто расширяющее —
-- все существующие коды (1–5 символов) остаются валидными, данные не мигрируют.
--
-- Расширение varchar в PostgreSQL не требует перезаписи таблицы и не перестраивает
-- уникальный индекс construction_objects_code_uq.

ALTER TABLE construction_objects ALTER COLUMN code TYPE varchar(6);
